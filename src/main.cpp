void setup()
{
  Wire.begin(5, 6);
  Wire.setClock(400000);
  u8g2.begin();
  matrix.begin();
  matrix.setBrightness(BRIGHTNESS); // Fissata a 15
  matrix.show();

  btnL.attach(PIN_BTN_L, INPUT_PULLUP);
  btnR.attach(PIN_BTN_R, INPUT_PULLUP);
  btnRot.attach(PIN_BTN_ROT, INPUT_PULLUP);
  btnDrop.attach(PIN_BTN_DROP, INPUT_PULLUP);
  btnL.interval(5);
  btnR.interval(5);
  btnRot.interval(5);
  btnDrop.interval(5);

  randomSeed(analogRead(2) + millis());
  for (int i = 0; i < 64; i++)
    fillArray[i] = i;

  resetGame();
  currentState = STATE_WEARABLE;
  currentEffect = 0;
}

void loop()
{
  btnL.update();
  btnR.update();
  btnRot.update();
  btnDrop.update();

  switch (currentState)
  {
  case STATE_WEARABLE:
    if (btnL.pressed())
    {
      currentEffect--;
      if (currentEffect < 0)
        currentEffect = TOTAL_EFFECTS - 1;
      matrix.clear();
      resetGame();
      stepCounter = 0;
      filledCount = 0;
      currentFrame = 0;
    }
    if (btnR.pressed())
    {
      currentEffect++;
      if (currentEffect >= TOTAL_EFFECTS)
        currentEffect = 0;
      matrix.clear();
      resetGame();
      stepCounter = 0;
      filledCount = 0;
      currentFrame = 0;
    }

    if (btnDrop.pressed())
    {
      resetGame();
      currentState = STATE_GAME;
      matrix.setBrightness(BRIGHTNESS);
      for (int i = 0; i < 3; i++)
      {
        matrix.fill(matrix.Color(50, 50, 50));
        matrix.show();
        delay(100);
        matrix.clear();
        matrix.show();
        delay(100);
      }
    }

    // 1. Aggiorna i LED
    runWearableEffects();

    // 2. Aggiorna il Display (ANIMAZIONI MULTIPLE)
    if (currentEffect == 1)
    {
      // EFFETTO 2: Arcobaleno LED + Nuvola OLED
      if (millis() - oledAnimTimer >= FRAME_DELAY)
      {
        oledAnimTimer = millis();
        currentFrame = (currentFrame + 1) % 25; // 25 Frame della Nuvola

        u8g2.clearBuffer();
        u8g2.drawBitmap(20, 4, 4, FRAME_HEIGHT, frames_cloud[currentFrame]);
        u8g2.sendBuffer();
      }
    }
    else if (currentEffect == 2)
    {
      // EFFETTO 3: Matrix Rain LED + Running Infinity OLED
      if (millis() - oledAnimTimer >= FRAME_DELAY)
      {
        oledAnimTimer = millis();
        currentFrame = (currentFrame + 1) % 28; // 28 Frame dell'Infinito

        u8g2.clearBuffer();
        u8g2.drawBitmap(20, 4, 4, FRAME_HEIGHT, frames_infinity[currentFrame]);
        u8g2.sendBuffer();
      }
    }
    else if (currentEffect == 3)
    {
      // EFFETTO 4: Stroboscopio Glitch LED + Occhio OLED
      if (millis() - oledAnimTimer >= FRAME_DELAY)
      {
        oledAnimTimer = millis();
        currentFrame = (currentFrame + 1) % 24; // 24 Frame dell'Occhio

        u8g2.clearBuffer();
        u8g2.drawBitmap(20, 4, 4, FRAME_HEIGHT, frames_eye[currentFrame]);
        u8g2.sendBuffer();
      }
    }
    else if (currentEffect == 4) { 
         // EFFETTO 5: Warm Pulse LED + Activity OLED
         if (millis() - oledAnimTimer >= FRAME_DELAY) {
            oledAnimTimer = millis();
            currentFrame = (currentFrame + 1) % 20; // 20 Frame di Activity
            
            u8g2.clearBuffer();
            u8g2.drawBitmap(20, 4, 4, FRAME_HEIGHT, frames_activity[currentFrame]);
            u8g2.sendBuffer();
         }
      }
    else
    {
      // MENU STANDARD PER TUTTI GLI ALTRI EFFETTI
      u8g2.clearBuffer();
      u8g2.setFont(u8g2_font_profont12_tr);
      u8g2.drawStr(15, 10, "TETRIS");
      u8g2.setFont(u8g2_font_profont10_tr);
      u8g2.setCursor(0, 25);
      u8g2.print("EFFETTO: ");
      u8g2.print(currentEffect + 1);
      u8g2.setCursor(0, 38);
      u8g2.print("[DROP] TO PLAY");
      u8g2.sendBuffer();
    }
    break;

  case STATE_GAME:
    runGameLogic();
    drawGame();
    u8g2.clearBuffer();
    u8g2.setFont(u8g2_font_profont10_tr);
    u8g2.setCursor(0, 8);
    u8g2.print("SCORE: ");
    u8g2.print(score);
    u8g2.setCursor(0, 18);
    u8g2.print("LINES: ");
    u8g2.print(linesCleared);
    u8g2.setCursor(0, 35);
    u8g2.print("LVL: ");
    u8g2.print(linesCleared / 5 + 1);
    u8g2.sendBuffer();
    break;

  case STATE_GAMEOVER:
    if (btnDrop.pressed() || btnRot.pressed())
    {
      currentState = STATE_WEARABLE;
      currentEffect = 0;
    }
    if ((millis() / 500) % 2 == 0)
    {
      u8g2.clearBuffer();
      u8g2.setFont(u8g2_font_profont12_tr);
      u8g2.drawStr(10, 15, "GAME");
      u8g2.drawStr(10, 28, "OVER");
      u8g2.setFont(u8g2_font_profont10_tr);
      u8g2.setCursor(5, 39);
      u8g2.print("SCORE: ");
      u8g2.print(score);
      u8g2.sendBuffer();
    }
    break;
  }
}

int getPixelIndex(int x, int y)
{
  if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT)
    return -1;
  int physicalX = INVERT_X ? (WIDTH - 1 - x) : x;
  int physicalY = INVERT_Y ? (HEIGHT - 1 - y) : y;
  if (IS_ZIGZAG)
    return (physicalY % 2 == 0) ? ((physicalY * WIDTH) + physicalX) : ((physicalY * WIDTH) + (WIDTH - 1 - physicalX));
  return (physicalY * WIDTH) + physicalX;
}

