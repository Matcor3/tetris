// Logica Gioco e Rendering...
void drawGame()
{
  matrix.clear();
  for (int y = 0; y < HEIGHT; y++)
  {
    for (int x = 0; x < WIDTH; x++)
    {
      if (grid[x][y] != 0)
      {
        int idx = getPixelIndex(x, y);
        if (idx != -1)
          matrix.setPixelColor(idx, grid[x][y]);
      }
    }
  }
  if (currentState == STATE_GAME || currentState == STATE_WEARABLE)
  {
    for (int i = 0; i < 4; i++)
    {
      int rx, ry;
      getBlockPos(playerPiece.type, playerPiece.rotation, i, rx, ry);
      int fx = playerPiece.x + rx, fy = playerPiece.y + ry;
      int idx = getPixelIndex(fx, fy);
      if (idx != -1)
        matrix.setPixelColor(idx, playerPiece.color);
    }
  }
  matrix.show();
}

void getBlockPos(int type, int rot, int pIdx, int &rx, int &ry)
{
  int x = SHAPES[type][pIdx * 2], y = SHAPES[type][pIdx * 2 + 1];
  for (int i = 0; i < rot; i++)
  {
    int temp = x;
    x = -y;
    y = temp;
  }
  rx = x;
  ry = y;
}
bool isValid(Piece p, int dx, int dy, int newRot)
{
  for (int i = 0; i < 4; i++)
  {
    int rx, ry;
    getBlockPos(p.type, newRot, i, rx, ry);
    int fx = p.x + dx + rx, fy = p.y + dy + ry;
    if (fx < 0 || fx >= WIDTH || fy >= HEIGHT)
      return false;
    if (fy >= 0 && grid[fx][fy] != 0)
      return false;
  }
  return true;
}
void runGameLogic()
{
  if (btnL.pressed() && isValid(playerPiece, -1, 0, playerPiece.rotation))
    playerPiece.x--;
  if (btnR.pressed() && isValid(playerPiece, 1, 0, playerPiece.rotation))
    playerPiece.x++;
  if (btnRot.pressed())
  {
    int newRot = (playerPiece.rotation + 1) % 4;
    if (isValid(playerPiece, 0, 0, newRot))
      playerPiece.rotation = newRot;
  }
  if (btnDrop.pressed())
  {
    while (isValid(playerPiece, 0, 1, playerPiece.rotation))
      playerPiece.y++;
    lockPiece(playerPiece);
    lastDropTime = millis();
  }
  if (millis() - lastDropTime > dropInterval)
  {
    if (isValid(playerPiece, 0, 1, playerPiece.rotation))
      playerPiece.y++;
    else
      lockPiece(playerPiece);
    lastDropTime = millis();
  }
}
void lockPiece(Piece &p)
{
  for (int i = 0; i < 4; i++)
  {
    int rx, ry;
    getBlockPos(p.type, p.rotation, i, rx, ry);
    int fx = p.x + rx, fy = p.y + ry;
    if (fy >= 0 && fy < HEIGHT && fx >= 0 && fx < WIDTH)
      grid[fx][fy] = p.color;
  }
  checkLines();
  spawnPiece(p);
  if (!isValid(p, 0, 0, p.rotation))
  {
    if (currentState == STATE_GAME)
      currentState = STATE_GAMEOVER;
    else
      resetGame();
  }
}
void checkLines()
{
  for (int y = HEIGHT - 1; y >= 0; y--)
  {
    bool full = true;
    for (int x = 0; x < WIDTH; x++)
      if (grid[x][y] == 0)
        full = false;
    if (full)
    {
      for (int x = 0; x < WIDTH; x++)
      {
        int idx = getPixelIndex(x, y);
        if (idx != -1)
          matrix.setPixelColor(idx, matrix.Color(255, 255, 255));
      }
      matrix.show();
      delay(40);
      for (int ny = y; ny > 0; ny--)
        for (int x = 0; x < WIDTH; x++)
          grid[x][ny] = grid[x][ny - 1];
      for (int x = 0; x < WIDTH; x++)
        grid[x][0] = 0;
      score += 100;
      linesCleared++;
      dropInterval = max(100, 800 - (linesCleared * 20));
      y++;
    }
  }
}
void spawnPiece(Piece &p)
{
  p.type = random(7);
  p.rotation = 0;
  p.x = 3;
  p.y = -1;
  p.color = COLORS[p.type];
}
void resetGame()
{
  memset(grid, 0, sizeof(grid));
  score = 0;
  linesCleared = 0;
  dropInterval = 800;
  spawnPiece(playerPiece);
}